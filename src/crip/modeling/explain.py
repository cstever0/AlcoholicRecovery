"""Explainability and feature attribution engine for CRIP recovery modeling.

DISCLAIMER:
Provides local and global feature attribution for synthetic predictive models.
Feature contributions represent statistical associations under synthetic cohort assumptions
and MUST NEVER be interpreted as causal treatment effects or direct patient prognoses.
"""

from __future__ import annotations

import logging
from typing import Any, Dict, List, Optional, Tuple, Union

import numpy as np
import pandas as pd
from sklearn.pipeline import Pipeline

logger = logging.getLogger("crip.modeling.explain")


def extract_preprocessed_feature_names(pipeline: Pipeline) -> List[str]:
    """Retrieve explicit feature names generated by the preprocessing ColumnTransformer."""
    preprocessor = pipeline.named_steps["prep"]
    try:
        names = list(preprocessor.get_feature_names_out())
    except Exception:
        # Fallback naming if get_feature_names_out is unavailable
        names = []
        for name, transformer, cols in preprocessor.transformers_:
            if name == "remainder" or transformer == "drop":
                continue
            if hasattr(transformer, "named_steps") and "ohe" in transformer.named_steps:
                ohe = transformer.named_steps["ohe"]
                try:
                    cat_names = list(ohe.get_feature_names_out(cols))
                    names.extend(cat_names)
                except Exception:
                    names.extend([f"cat__{c}" for c in cols])
            else:
                names.extend([f"{name}__{c}" for c in cols])
    return names


def get_global_logistic_regression_weights(pipeline: Pipeline) -> pd.DataFrame:
    """Extract global coefficients and odds ratios from a trained logistic regression pipeline.

    Returns:
        DataFrame containing feature names, log-odds coefficients (beta), odds ratios (exp(beta)),
        absolute magnitude, and qualitative clinical direction.
    """
    clf = pipeline.named_steps["clf"]
    if not hasattr(clf, "coef_"):
        raise ValueError("Provided pipeline classifier does not have a linear coef_ attribute.")

    feature_names = extract_preprocessed_feature_names(pipeline)
    coefs = clf.coef_[0]

    if len(feature_names) != len(coefs):
        feature_names = [f"feature_{i}" for i in range(len(coefs))]

    records = []
    for name, beta in zip(feature_names, coefs):
        # Format human-readable feature name
        clean_name = name
        for prefix in ["num__", "cat__", "bin__"]:
            if clean_name.startswith(prefix):
                clean_name = clean_name[len(prefix):]

        odds_ratio = float(np.exp(beta))
        direction = "Promotes Recovery" if beta > 0 else "Inhibits Recovery"

        records.append({
            "raw_feature": name,
            "feature": clean_name,
            "coefficient_beta": round(float(beta), 4),
            "odds_ratio": round(odds_ratio, 4),
            "abs_magnitude": round(abs(float(beta)), 4),
            "direction": direction,
        })

    df = pd.DataFrame(records).sort_values(by="abs_magnitude", ascending=False).reset_index(drop=True)
    return df


def explain_patient_prediction(
    pipeline: Pipeline,
    patient_row: Union[pd.Series, Dict[str, Any], pd.DataFrame],
    baseline_lvef: Optional[float] = None,
) -> Dict[str, Any]:
    """Decompose an individual patient's simulated recovery prediction into feature contributions.

    Args:
        pipeline: Trained Scikit-learn Pipeline (prep + classifier).
        patient_row: Single-patient input data (baseline features).
        baseline_lvef: Optional baseline LVEF for narrative context.

    Returns:
        Dictionary with simulated probability, log-odds intercept, feature attributions,
        and plain-language research explanation.
    """
    if isinstance(patient_row, dict):
        df_single = pd.DataFrame([patient_row])
    elif isinstance(patient_row, pd.Series):
        df_single = pd.DataFrame([patient_row.to_dict()])
    else:
        df_single = patient_row.head(1).copy()

    for col in ["peth_available", "alcohol_history_available", "lge_available"]:
        if col in df_single.columns:
            df_single[col] = df_single[col].astype(float)

    preprocessor = pipeline.named_steps["prep"]
    clf = pipeline.named_steps["clf"]

    # Transform features
    X_trans = preprocessor.transform(df_single)
    feature_names = extract_preprocessed_feature_names(pipeline)

    prob = float(pipeline.predict_proba(df_single)[0, 1])
    intercept = float(clf.intercept_[0]) if hasattr(clf, "intercept_") else 0.0
    coefs = clf.coef_[0] if hasattr(clf, "coef_") else np.zeros(X_trans.shape[1])

    # Linear log-odds decomposition: z = intercept + sum(coef_j * x_j)
    x_vec = X_trans[0]
    contributions = coefs * x_vec
    total_z = intercept + np.sum(contributions)

    feature_attributions = []
    for name, raw_val, weight, contrib in zip(feature_names, x_vec, coefs, contributions):
        clean_name = name
        for prefix in ["num__", "cat__", "bin__"]:
            if clean_name.startswith(prefix):
                clean_name = clean_name[len(prefix):]

        # Only include non-zero or notable contributions
        if abs(contrib) > 0.001:
            odds_ratio_val = round(float(np.exp(weight)), 4)
            contrib_val = round(float(contrib), 4)
            feature_attributions.append({
                "feature": clean_name,
                "raw_value": round(float(raw_val), 4),
                "weight": round(float(weight), 4),
                "odds_ratio": odds_ratio_val,
                "attribution": contrib_val,
                "contribution_log_odds": contrib_val,
                "direction": "Promotes Recovery" if contrib > 0 else "Inhibits Recovery",
            })

    # Sort attributions by absolute contribution
    feature_attributions = sorted(feature_attributions, key=lambda x: abs(x["contribution_log_odds"]), reverse=True)

    # Narrative generation
    pos_top = [f"{a['feature']} (+{a['contribution_log_odds']:.2f})" for a in feature_attributions if a["contribution_log_odds"] > 0][:3]
    neg_top = [f"{a['feature']} ({a['contribution_log_odds']:.2f})" for a in feature_attributions if a["contribution_log_odds"] < 0][:3]

    narrative = (
        f"Under the specified synthetic cohort assumptions and assuming sustained 6-month abstinence, "
        f"the model estimates a {prob:.1%} simulated probability of meeting the primary recovery endpoint "
        f"(improvement of at least 10 percentage points in LVEF). "
    )
    if pos_top:
        narrative += f"Primary positive drivers: {', '.join(pos_top)}. "
    if neg_top:
        narrative += f"Primary negative constraints: {', '.join(neg_top)}."

    causal_warning = (
        "IMPORTANT RESEARCH CAUTION: Feature contributions represent observational associations "
        "under synthetic simulation parameters. They do NOT constitute causal effects or guarantee "
        "clinical recovery for an individual patient."
    )

    return {
        "simulated_recovery_probability": round(prob, 4),
        "log_odds_score": round(float(total_z), 4),
        "intercept": round(intercept, 4),
        "feature_attributions": feature_attributions,
        "narrative_explanation": narrative,
        "causal_disclaimer": causal_warning,
    }


def compute_linear_shap_values(
    pipeline: Pipeline,
    X_sample: pd.DataFrame,
) -> Dict[str, Any]:
    """Compute exact SHAP values for linear models analytically: phi_j = beta_j * (x_j - E[x_j])."""
    preprocessor = pipeline.named_steps["prep"]
    clf = pipeline.named_steps["clf"]

    X_trans = preprocessor.transform(X_sample)
    feature_names = extract_preprocessed_feature_names(pipeline)

    coefs = clf.coef_[0]
    intercept = float(clf.intercept_[0])

    # For standard scaled features, mean of scaled values is approximately 0
    # phi_j = coefs_j * (x_trans_j - mean_j)
    means = np.mean(X_trans, axis=0)
    shap_matrix = coefs * (X_trans - means)
    base_value = intercept + np.sum(coefs * means)

    mean_abs_shap = np.mean(np.abs(shap_matrix), axis=0)
    importance_df = pd.DataFrame({
        "feature": [f.replace("num__", "").replace("cat__", "").replace("bin__", "") for f in feature_names],
        "mean_abs_shap": np.round(mean_abs_shap, 4),
    }).sort_values(by="mean_abs_shap", ascending=False).reset_index(drop=True)

    return {
        "shap_values": shap_matrix,
        "base_value": round(float(base_value), 4),
        "feature_names": feature_names,
        "feature_importance": importance_df.to_dict(orient="records"),
    }
