"""Structured Research Demonstration Reporting for CRIP Multimodal Cases.

DISCLAIMER:
Generates structured Markdown, HTML, and JSON reports summarizing multimodal
imaging, synthetic biomarkers, recovery predictions, and feature attributions.
Strictly for clinical AI research demonstration. NOT for clinical patient care.
"""

from __future__ import annotations

import html
import json
import logging
from typing import Any, Dict, List, Optional

logger = logging.getLogger("crip.integration.reporting")


def generate_markdown_report(case_result: Dict[str, Any]) -> str:
    """Generate a clean, publication-ready GitHub-flavored Markdown research report."""
    case_id = case_result.get("case_id", "UNKNOWN-CASE")
    timestamp = case_result.get("timestamp", "N/A")
    status = case_result.get("status", "UNKNOWN")
    profile = case_result.get("profile", {})
    mri = case_result.get("mri_metrics", {})
    rec = case_result.get("recovery_prediction", {})
    exp = case_result.get("explanation", {})
    val = case_result.get("validation", {})

    lines: List[str] = [
        f"# CRIP Multimodal Research Case Report: {case_id}",
        "",
        "> [!WARNING]",
        "> ### CLINICAL RESEARCH DISCLAIMER — NOT FOR CLINICAL USE",
        "> This report is generated by the Cardiomyopathy Recovery Intelligence Platform (CRIP), an academic research proof of concept.",
        "> **Predictions are derived from synthetic simulation and MUST NEVER be used for clinical diagnosis, patient risk stratification, or clinical treatment decisions.**",
        "> Phosphatidylethanol (PEth) quantification reflects recent ethanol exposure and does not predict the severity of alcohol withdrawal syndrome.",
        "",
        "---",
        "",
        "## 1. Case Metadata & Scenario Identification",
        f"- **Case Identifier:** `{case_id}`",
        f"- **Execution Timestamp:** `{timestamp}`",
        f"- **Integration Status:** `{status}`",
        f"- **Scenario Classification:** `{profile.get('source_type', 'CONSTRUCTED_MULTIMODAL_SCENARIO')}`",
        f"- **ACDC MRI Subject:** `{profile.get('acdc_patient_id') or mri.get('patient_id') or 'N/A'}`",
        f"- **MRI Volumetric Method:** `{mri.get('method', 'AUTOMATED_UNET')}`",
        "",
        "## 2. Baseline Demographics & Clinical Characteristics",
        "| Parameter | Value | Source Provenance |",
        "| :--- | :--- | :--- |",
        f"| **Age** | {profile.get('age', 'N/A')} years | Synthetic/Reported |",
        f"| **Biological Sex** | {profile.get('biological_sex', 'N/A')} | Synthetic/Reported |",
        f"| **PEth (16:0/18:1)** | {profile.get('peth_value_ng_ml', 'N/A')} ng/mL | Simulated Biomarker |",
        f"| **PEth Risk Tier** | {profile.get('peth_risk_tier', 'N/A')} | Simulated Biomarker |",
        f"| **Reported Alcohol Intake** | {profile.get('reported_drinks_per_week', 'N/A')} drinks/week | Synthetic History |",
        f"| **Heavy Drinking Duration** | {profile.get('years_heavy_drinking', 'N/A')} years | Synthetic History |",
        f"| **Titin (*TTN*) Variant** | {profile.get('ttn_classification', 'NOT_TESTED')} | Simulated Genetics (ACMG-AMP) |",
        f"| **CMR LGE Scar** | {profile.get('lge_status', 'NEGATIVE')} ({profile.get('lge_pattern', 'NONE')}, {profile.get('lge_extent_percent', 0.0)}%) | Synthetic Tissue Characterization |",
        "",
        "## 3. Cardiac Magnetic Resonance (CMR) Volumetrics",
        "| Volumetric Metric | Value | Reference / Notes |",
        "| :--- | :--- | :--- |",
        f"| **LV End-Diastolic Volume (LVEDV)** | {mri.get('edv_ml', 'N/A')} mL | Derived from 3D MRI stack |",
        f"| **LV End-Systolic Volume (LVESV)** | {mri.get('esv_ml', 'N/A')} mL | Derived from 3D MRI stack |",
        f"| **LV Stroke Volume (LVSV)** | {mri.get('stroke_volume_ml', 'N/A')} mL | LVEDV - LVESV |",
        f"| **Baseline LVEF** | **{mri.get('baseline_lvef', 'N/A')}%** | Primary Volumetric Functional Baseline |",
        f"| **RV End-Diastolic Volume (RVEDV)** | {mri.get('rvedv_ml', 'N/A')} mL | Biventricular parameter |",
        f"| **RV Ejection Fraction (RVEF)** | {mri.get('rvef_percent', 'N/A')}% | Right ventricular systolic function |",
        f"| **Myocardial Mass** | {mri.get('myocardial_mass_g', 'N/A')} g | Assumes 1.05 g/mL density |",
        "",
    ]

    # Validation warnings
    warnings = val.get("warnings", [])
    if warnings:
        lines.extend([
            "### Data Consistency Warnings",
            *[f"- :warning: {w}" for w in warnings],
            "",
        ])

    # Recovery Prediction Section
    if rec:
        prob = rec.get("recovery_probability", 0.0)
        tier = rec.get("propensity_tier", "N/A")
        bin_pred = "Likely Recovery (ΔLVEF ≥ 10%)" if rec.get("binary_prediction") == 1 else "Unlikely Recovery (ΔLVEF < 10%)"

        lines.extend([
            "## 4. Simulated 6-Month Recovery Prediction",
            r"- **Target Definition:** Clinically significant reverse remodeling ($\Delta \text{LVEF} \ge 10\%$ at 6 months).",
            f"- **Assumed Behavioral Scenario:** `{rec.get('assumed_scenario', 'SUSTAINED_ABSTINENCE')}`",
            f"- **Simulated Probability of Recovery:** **{prob * 100.0:.2f}%**",
            f"- **Recovery Propensity Tier:** `{tier}`",
            f"- **Model Binary Output:** `{bin_pred}`",
            f"- **Model Version:** `{rec.get('model_version', 'v1.0-m3b')}`",
            "",
        ])

    # Missing Data & Plausible Sensitivity Analysis Section
    sens = case_result.get("sensitivity_analysis", {})
    if sens and sens.get("has_missing_modalities"):
        miss_mods = sens.get("missing_modalities", [])
        sens_range = sens.get("plausible_sensitivity_range")
        lines.extend([
            "### ⚠️ Missing Modality Notice & Plausible Sensitivity Analysis",
            "> [!IMPORTANT]",
            "> **CRITICAL MISSING DATA WARNING:** One or more primary prognostic modalities are missing from this clinical profile.",
            f"> The baseline prediction relies on empirical median/mode imputation: *{sens.get('imputation_method')}*.",
            "",
            "**Missing Clinical Modalities:**",
            *[f"- :warning: **{m}** (Unmeasured / Withheld)" for m in miss_mods],
            "",
        ])
        if sens_range:
            p_pess = sens_range.get("pessimistic_probability", 0.0) * 100.0
            p_base = sens_range.get("baseline_imputed_probability", 0.0) * 100.0
            p_opt = sens_range.get("optimistic_probability", 0.0) * 100.0
            lines.extend([
                "| Plausible Assumption Scenario | Simulated Recovery Probability | Modeling Basis |",
                "| :--- | :--- | :--- |",
                f"| **Pessimistic Plausible Bound** | **{p_pess:.1f}%** | Assumes low toxic insult, pathogenic *TTN*, midwall LGE fibrosis |",
                f"| **Baseline Imputed Point Estimate** | **{p_base:.1f}%** | Median/mode training distribution imputation with indicator flags |",
                f"| **Optimistic Plausible Bound** | **{p_opt:.1f}%** | Assumes high reversible alcohol exposure, wildtype *TTN*, absent LGE |",
                "",
                f"> [!CAUTION]",
                f"> **Interpretation Disclaimer:** {sens_range.get('disclaimer')}",
                "",
            ])

    # Explainability Section
    if exp:
        attribs = exp.get("feature_attributions", [])
        lines.extend([
            "## 5. Model Explainability & Attribution Decomposition",
            f"- **Log-Odds Intercept (Prior Baseline):** `{exp.get('intercept', 0.0)}`",
            "",
            "| Feature | Value | Coefficient (β) | Odds Ratio | Attribution (Δ Log-Odds) | Qualitative Direction |",
            "| :--- | :--- | :--- | :--- | :--- | :--- |",
        ])
        for att in attribs[:10]:
            lines.append(
                f"| `{att.get('feature')}` | {att.get('raw_value')} | {att.get('weight')} | "
                f"{att.get('odds_ratio')} | {att.get('attribution')} | {att.get('direction')} |"
            )
        lines.extend([
            "",
            "### Clinical Review Considerations",
            "- **Abstinence Management:** Sudden alcohol cessation carries risk of Acute Alcohol Withdrawal Syndrome; medically supervised detoxification protocol is mandatory.",
            "- **Genetics:** If pathogenic *TTN* variants are present, consider familial cardiomyopathy screening and medical genetics consultation.",
            "- **Guideline-Directed Medical Therapy (GDMT):** Recovery in cardiomyopathy requires quadruple neurohormonal blockade irrespective of lifestyle changes.",
            "",
            "---",
            "*Report generated by CRIP v1.0 Integration Layer — Confidential Research Material.*",
        ])

    return "\n".join(lines)


